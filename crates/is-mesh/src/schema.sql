CREATE TABLE zz_mesh_format(singleton INTEGER PRIMARY KEY CHECK(singleton=1), version INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS workers(slot INTEGER PRIMARY KEY, incarnation INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS units(id BLOB PRIMARY KEY, slot INTEGER NOT NULL, inc INTEGER NOT NULL,
 gen INTEGER NOT NULL, rev INTEGER NOT NULL DEFAULT 0, frozen BLOB, progress BLOB, floor INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS names(id BLOB PRIMARY KEY, unit BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS documents(id BLOB PRIMARY KEY, unit BLOB NOT NULL REFERENCES units(id),
 rev INTEGER NOT NULL, deleted INTEGER NOT NULL, body BLOB NOT NULL);
CREATE INDEX IF NOT EXISTS doc_unit ON documents(unit,id);
CREATE INDEX IF NOT EXISTS doc_revision ON documents(unit,rev);
CREATE TABLE IF NOT EXISTS clock(mark INTEGER NOT NULL);
INSERT INTO clock SELECT 0 WHERE NOT EXISTS(SELECT 1 FROM clock);
CREATE TABLE IF NOT EXISTS notices(slot INTEGER NOT NULL,unit BLOB NOT NULL,mark INTEGER NOT NULL,PRIMARY KEY(slot,unit));
CREATE INDEX IF NOT EXISTS worker_notices ON notices(slot,mark);
CREATE TRIGGER IF NOT EXISTS committed_unit AFTER UPDATE OF rev,gen ON units BEGIN
 UPDATE clock SET mark=mark+1;
 INSERT OR REPLACE INTO notices VALUES(OLD.slot,OLD.id,(SELECT mark FROM clock));
 INSERT OR REPLACE INTO notices VALUES(NEW.slot,NEW.id,(SELECT mark FROM clock));
END;
CREATE TABLE IF NOT EXISTS requirements(unit BLOB NOT NULL REFERENCES units(id), key BLOB NOT NULL, manifest BLOB NOT NULL, PRIMARY KEY(unit,key));
CREATE TABLE IF NOT EXISTS sessions(id BLOB PRIMARY KEY, actor BLOB NOT NULL, last INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS results(session BLOB NOT NULL, seq INTEGER NOT NULL, request BLOB NOT NULL, receipt BLOB NOT NULL,
 PRIMARY KEY(session,seq));
CREATE TABLE IF NOT EXISTS permits(unit BLOB NOT NULL, session BLOB NOT NULL, seq INTEGER NOT NULL, request BLOB NOT NULL,
 slot INTEGER NOT NULL, inc INTEGER NOT NULL, gen INTEGER NOT NULL, rev INTEGER NOT NULL, PRIMARY KEY(unit,session,seq));
CREATE TABLE IF NOT EXISTS handoffs(ticket BLOB PRIMARY KEY, unit BLOB NOT NULL, source BLOB NOT NULL, target BLOB NOT NULL,
 phase INTEGER NOT NULL, rev INTEGER, manifest BLOB);
CREATE UNIQUE INDEX IF NOT EXISTS one_transfer ON handoffs(unit) WHERE phase<3;
CREATE TABLE IF NOT EXISTS handoff_records(ticket BLOB NOT NULL REFERENCES handoffs(ticket) ON DELETE CASCADE,id BLOB NOT NULL,body BLOB NOT NULL,PRIMARY KEY(ticket,id));
CREATE TABLE IF NOT EXISTS credentials(slot INTEGER PRIMARY KEY, incarnation INTEGER NOT NULL, fingerprint BLOB UNIQUE NOT NULL);
CREATE TABLE IF NOT EXISTS player_credentials(fingerprint BLOB PRIMARY KEY, actor BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS handoff_checkpoints(ticket BLOB NOT NULL REFERENCES handoffs(ticket) ON DELETE CASCADE,id BLOB NOT NULL,body BLOB NOT NULL,PRIMARY KEY(ticket,id));
CREATE TABLE IF NOT EXISTS addresses(slot INTEGER PRIMARY KEY, inc INTEGER NOT NULL,address TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS departures(unit BLOB NOT NULL,id BLOB NOT NULL,rev INTEGER NOT NULL,PRIMARY KEY(unit,id));
CREATE INDEX IF NOT EXISTS departed_revision ON departures(unit,rev);
CREATE TABLE IF NOT EXISTS member_data(object BLOB NOT NULL,unit BLOB NOT NULL,key BLOB NOT NULL,manifest BLOB NOT NULL,PRIMARY KEY(object,key));
CREATE INDEX IF NOT EXISTS member_data_unit ON member_data(unit,key);
